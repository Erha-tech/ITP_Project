# Константа для хранения имени файла, куда будет сохраняться лучший результат (рекорд)
SCORE_FILE = "highscore.json"

def load_high_score():
    """
    Функция загрузки рекорда из JSON-файла.
    Если файл отсутствует или поврежден, возвращает 0.
    """
    # Проверяем, существует ли файл с рекордом в текущей директории
    if not os.path.exists(SCORE_FILE):
        return 0 # Если файла нет, возвращаем дефолтное значение 0
    try:
        # Открываем файл для чтения с автоматическим закрытием потока (контекстный менеджер with)
        with open(SCORE_FILE, "r") as file:
            # Десериализуем данные из формата JSON в стандартный словарь Python
            data = json.load(file)
            # Извлекаем значение по ключу "high_score", если ключа нет — возвращаем 0
            return data.get("high_score", 0)
    # Обработка исключений: если JSON некорректен (JSONDecodeError) или произошла ошибка ввода-вывода (IOError)
    except (json.JSONDecodeError, IOError) as e:
        # Выводим диагностическое сообщение об ошибке в консоль
        print(f"Ошибка чтения файла: {e}")
        return 0 # Возвращаем 0 в случае сбоя, чтобы предотвратить падение программы

def save_high_score(score):
    """
    Функция сохранения нового рекорда в JSON-файл.
    Принимает текущее максимальное значение счета (score).
    """
    try:
        # Открываем файл для записи. Если файла нет, он создастся; если есть — перезапишется
        with open(SCORE_FILE, "w") as file:
            # Сериализуем словарь с рекордом в строку формата JSON и записываем в файл
            json.dump({"high_score": score}, file)
    # Перехватываем любые критические исключения при записи, чтобы избежать аварийного завершения игры
    except Exception as e:
        # Логируем ошибку сохранения в консоль
        print(f"Ошибка сохранения файла: {e}")
